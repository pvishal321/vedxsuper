    fun getIntelligence(symbol: String): OptionIntelligence? {
        val state = optionStates[symbol] ?: return null
        val candles = state.candleBuilder.candles.value
        val optionSt = state.stEngine.calculate(candles) ?: return null
        val indexSt = indexStEngine.calculate(indexCandleBuilder.candles.value) ?: return null
        return OptionIntelligence(
            fake = fakeReversalEngine.analyze(candles, optionSt, state.strength, currentStructure),
            liquidity = liquidityEngine.analyze(state.lastBid, state.lastAsk, state.lastLtp),
            correlation = correlationEngine.calculate(indexSt, optionSt, symbol)
        )
    }

